-- ============================================================
-- 4. Validaciones
-- ============================================================

DO $$
DECLARE
    study_plan_count INTEGER;
    relation_count INTEGER;
    invalid_institution_refs INTEGER;
    invalid_plan_refs INTEGER;
    duplicate_relations INTEGER;
    relations_without_secondary INTEGER;
BEGIN
    SELECT COUNT(*) INTO study_plan_count
    FROM study_plans;

    IF study_plan_count <> 72 THEN
        RAISE EXCEPTION
            'Validación 005d falló: se esperaban 72 planes y hay %',
            study_plan_count;
    END IF;

    SELECT COUNT(*) INTO relation_count
    FROM institution_study_plans;

    IF relation_count <> 2328 THEN
        RAISE EXCEPTION
            'Validación 005d falló: se esperaban 2328 relaciones y hay %',
            relation_count;
    END IF;

    SELECT COUNT(*)
    INTO invalid_institution_refs
    FROM institution_study_plans isp
    LEFT JOIN institutions i
        ON i.id = isp.institution_id
    WHERE i.id IS NULL;

    IF invalid_institution_refs <> 0 THEN
        RAISE EXCEPTION
            'Validación 005d falló: hay % relaciones con institución inválida',
            invalid_institution_refs;
    END IF;

    SELECT COUNT(*)
    INTO invalid_plan_refs
    FROM institution_study_plans isp
    LEFT JOIN study_plans sp
        ON sp.id = isp.study_plan_id
    WHERE sp.id IS NULL;

    IF invalid_plan_refs <> 0 THEN
        RAISE EXCEPTION
            'Validación 005d falló: hay % relaciones con plan inválido',
            invalid_plan_refs;
    END IF;

    SELECT COUNT(*)
    INTO duplicate_relations
    FROM (
        SELECT institution_id, study_plan_id, COUNT(*) AS cantidad
        FROM institution_study_plans
        GROUP BY institution_id, study_plan_id
        HAVING COUNT(*) > 1
    ) duplicates;

    IF duplicate_relations <> 0 THEN
        RAISE EXCEPTION
            'Validación 005d falló: hay % relaciones institución-plan duplicadas',
            duplicate_relations;
    END IF;

    SELECT COUNT(*)
    INTO relations_without_secondary
    FROM institution_study_plans isp
    WHERE NOT EXISTS (
        SELECT 1
        FROM institution_levels il
        WHERE il.institution_id = isp.institution_id
          AND il.level = 'Secundario'
    );

    IF relations_without_secondary <> 0 THEN
        RAISE EXCEPTION
            'Validación 005d falló: hay % relaciones de planes sin nivel Secundario',
            relations_without_secondary;
    END IF;

    RAISE NOTICE
        '005d OK: % planes, % relaciones, todas las relaciones corresponden a instituciones con nivel Secundario.',
        study_plan_count,
        relation_count;
END $$;

COMMIT;
