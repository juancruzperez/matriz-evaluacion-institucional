    duplicate_count INTEGER;
    unresolved_count INTEGER;
BEGIN
    SELECT COUNT(*) INTO source_count
    FROM _study_plan_source;

    IF source_count <> 2328 THEN
        RAISE EXCEPTION
            'Preflight abortado: la fuente contiene % relaciones; se esperaban 2328',
            source_count;
    END IF;

    SELECT COUNT(*) INTO duplicate_count
    FROM (
        SELECT cue, plan_code, plan_name
        FROM _study_plan_source
        GROUP BY cue, plan_code, plan_name
        HAVING COUNT(*) > 1
    ) d;

    IF duplicate_count <> 0 THEN
        RAISE EXCEPTION
            'Preflight abortado: hay % relaciones duplicadas en la fuente',
            duplicate_count;
    END IF;

    SELECT COUNT(*) INTO unresolved_count
    FROM _study_plan_source s
    LEFT JOIN institutions i
        ON i.cue = s.cue
    LEFT JOIN study_plans sp
        ON sp.nombre = s.plan_name
    LEFT JOIN institution_levels il
        ON il.institution_id = i.id
       AND il.level = 'Secundario'
       AND il.modalidad = CASE
            WHEN s.plan_code = 2 THEN 'Común'
            WHEN s.plan_code = 7 THEN 'Jóvenes y Adultos'
          END
    WHERE i.id IS NULL
       OR sp.id IS NULL
       OR il.id IS NULL;

    IF unresolved_count <> 0 THEN
        RAISE EXCEPTION
            'Preflight abortado: hay % relaciones que no pueden resolverse contra institutions/study_plans/institution_levels',
            unresolved_count;
    END IF;
END $$;

UPDATE institution_study_plans isp
SET institution_level_id = il.id
FROM institutions i
JOIN _study_plan_source s
    ON s.cue = i.cue
JOIN study_plans sp
    ON sp.nombre = s.plan_name
JOIN institution_levels il
    ON il.institution_id = i.id
   AND il.level = 'Secundario'
   AND il.modalidad = CASE
        WHEN s.plan_code = 2 THEN 'Común'
        WHEN s.plan_code = 7 THEN 'Jóvenes y Adultos'
      END
WHERE isp.institution_id = i.id
  AND isp.study_plan_id = sp.id;

DO $$
DECLARE
    null_count INTEGER;
    mismatch_count INTEGER;
BEGIN
    SELECT COUNT(*) INTO null_count
    FROM institution_study_plans
    WHERE institution_level_id IS NULL;

    IF null_count <> 0 THEN
        RAISE EXCEPTION
            'Validación abortada: quedaron % relaciones sin institution_level_id',
            null_count;
    END IF;

    SELECT COUNT(*) INTO mismatch_count
    FROM institution_study_plans isp
    JOIN institutions i
      ON i.id = isp.institution_id
    JOIN institution_levels il
      ON il.id = isp.institution_level_id
    WHERE il.institution_id <> isp.institution_id;

    IF mismatch_count <> 0 THEN
        RAISE EXCEPTION
            'Validación abortada: hay % relaciones con institution_level de otra institución',
            mismatch_count;
    END IF;
END $$;

